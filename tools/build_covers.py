#!/usr/bin/env python3
"""Convert six album covers to embedded Nintendo DS RGB555 images."""

from pathlib import Path
import subprocess
import struct

ROOT = Path(__file__).resolve().parent.parent
INPUT = ROOT / "assets" / "covers"
OUTPUT = ROOT / "source" / "covers_generated.h"

ALBUMS = [
    "sempiternal",
    "suicide_season",
    "thats_the_spirit",
    "amo",
    "survival_horror",
    "count_your_blessings",
]

SIZE = 64
COUNT = 6


def placeholder(index):
    colors = [
        (90, 75, 105),
        (125, 35, 35),
        (50, 55, 90),
        (140, 65, 110),
        (45, 100, 85),
        (100, 45, 95),
    ]

    base = colors[index]
    pixels = bytearray()

    for y in range(SIZE):
        for x in range(SIZE):
            dx = x - 32
            dy = y - 32
            distance = dx * dx + dy * dy

            if 90 < distance < 650:
                rgb = (15, 15, 24)
            elif distance <= 90:
                rgb = (205, 190, 225)
            else:
                rgb = base

            pixels.extend(rgb)

    return bytes(pixels)


def read_cover(index):
    for ext in ("jpg", "jpeg", "png", "webp"):
        path = INPUT / f"{ALBUMS[index]}.{ext}"

        if not path.is_file():
            continue

        result = subprocess.run(
            [
                "magick",
                str(path),
                "-auto-orient",
                "-resize", "64x64^",
                "-gravity", "center",
                "-extent", "64x64",
                "-alpha", "remove",
                "-depth", "8",
                "rgb:-",
            ],
            capture_output=True,
            check=True,
        )

        if len(result.stdout) != SIZE * SIZE * 3:
            raise RuntimeError(f"Invalid pixel data: {path}")

        print(f"[OK] {path.name}")
        return result.stdout

    print(f"[--] Cover {index + 1:02d} missing: using placeholder")
    return placeholder(index)


def encode_rgb555(rgb):
    output = []

    for i in range(0, len(rgb), 3):
        r, g, b = rgb[i:i + 3]

        pixel = (
            0x8000
            | (r >> 3)
            | ((g >> 3) << 5)
            | ((b >> 3) << 10)
        )

        output.append(pixel)

    return output


def main():
    INPUT.mkdir(parents=True, exist_ok=True)

    with OUTPUT.open("w") as f:
        f.write("/* Generated by tools/build_covers.py */\n")
        f.write("#ifndef DSI_COVERS_GENERATED_H\n")
        f.write("#define DSI_COVERS_GENERATED_H\n\n")
        f.write("#include <stdint.h>\n\n")
        f.write(
            f"static const uint16_t albumCovers[{COUNT}]"
            f"[{SIZE * SIZE}] = {{\n"
        )

        for index in range(COUNT):
            pixels = encode_rgb555(read_cover(index))

            f.write("    {\n")

            for offset in range(0, len(pixels), 12):
                chunk = pixels[offset:offset + 12]
                f.write(
                    "        "
                    + ", ".join(f"0x{p:04X}" for p in chunk)
                    + ",\n"
                )

            f.write("    },\n")

        f.write("};\n\n#endif\n")

    print(f"\nGenerated: {OUTPUT}")


if __name__ == "__main__":
    main()
